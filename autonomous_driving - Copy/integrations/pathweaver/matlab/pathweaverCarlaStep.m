function responseJson = pathweaverCarlaStep(requestJson)
%PATHWEAVERCARLASTEP Plan one local CARLA step using the PathWeaver core.
persistent behaviorState
request = jsondecode(requestJson);
validateRequest(request);
cfg = defaultConfig();
cfg.mode = "risk-aware";
cfg.scenario.roadLengthM = request.roadLengthM;
cfg.scenario.nominalWidthM = 2 * request.roadHalfWidthM;
cfg.planner.routeSpeedMps = request.routeSpeedMps;
cfg.scenario.goalPositionWorldM = [request.roadLengthM - 5, 0];
scenario = struct( ...
    'name', "carla_local", ...
    'timeS', request.timestampS, ...
    'goalPositionWorldM', cfg.scenario.goalPositionWorldM, ...
    'staticObstacles', makeStaticObstacle(request.staticObstacle));
world = struct( ...
    'timestampS', request.timestampS, ...
    'ego', makeEgo(request.ego), ...
    'agents', makeAgents(request.agents), ...
    'staticObstacles', scenario.staticObstacles, ...
    'source', "CARLA SIMULATOR GROUND TRUTH");
predictions = pathweaver.prediction.predictAgents( ...
    world.agents, world.timestampS, cfg);
planner = pathweaver.planning.planTrajectories( ...
    world, predictions, scenario, cfg);
planner.minimumTtcS = pathweaver.planning.minimumTtc( ...
    world.ego, world.agents, cfg.horizon, cfg, scenario.staticObstacles);
if isempty(behaviorState) || request.reset
    behaviorState = pathweaver.behavior.initialState();
end
[behaviorState, ~] = pathweaver.behavior.updateState( ...
    behaviorState, planner, world, scenario, request.collision, cfg);
planner.behaviorState = behaviorState.name;
planner.emergencyFlag = planner.emergencyFlag || ...
    behaviorState.name == "EMERGENCY_BRAKE" || request.collision;
selected = planner.selectedTrajectory;
ttc = planner.minimumTtcS;
if ~isfinite(ttc)
    ttc = -1;
end
response = struct( ...
    'timestampS', request.timestampS, ...
    'selectedTrajectory', struct( ...
        'positionsWorldM', selected.positionsWorldM, ...
        'timestampsS', selected.timestampsS, ...
        'speedsMps', selected.speedsMps, ...
        'accelerationsMps2', selected.accelerationsMps2, ...
        'isFeasible', selected.isFeasible), ...
    'riskScore', planner.riskScore, ...
    'minimumTtcS', ttc, ...
    'behaviorState', char(planner.behaviorState), ...
    'emergencyFlag', planner.emergencyFlag, ...
    'lookaheadM', cfg.control.lookaheadBaseM + ...
        cfg.control.lookaheadGainS * world.ego.speedMps, ...
    'planningLatencyS', planner.planningLatencyS);
responseJson = jsonencode(response);
end

function validateRequest(request)
required = {'timestampS', 'ego', 'agents', 'roadHalfWidthM', ...
    'roadLengthM', 'routeSpeedMps', 'staticObstacle', 'collision', 'reset'};
assert(all(isfield(request, required)), ...
    'PathWeaver:InvalidRequest', 'Request is missing required fields.');
assert(isfinite(request.timestampS) && request.timestampS >= 0, ...
    'PathWeaver:InvalidRequest', 'timestampS must be finite and nonnegative.');
assert(isfinite(request.roadHalfWidthM) && request.roadHalfWidthM > 1.5, ...
    'PathWeaver:InvalidRequest', 'roadHalfWidthM must exceed 1.5 m.');
assert(isfinite(request.roadLengthM) && request.roadLengthM > 20, ...
    'PathWeaver:InvalidRequest', 'roadLengthM must exceed 20 m.');
assert(isfinite(request.routeSpeedMps) && request.routeSpeedMps > 0, ...
    'PathWeaver:InvalidRequest', 'routeSpeedMps must be positive.');
end

function ego = makeEgo(input)
required = {'positionWorldM', 'headingRad', 'speedMps', ...
    'accelerationMps2', 'steeringRad', 'timestampS'};
assert(all(isfield(input, required)), ...
    'PathWeaver:InvalidRequest', 'Ego state is incomplete.');
ego = input;
ego.positionWorldM = reshape(input.positionWorldM, 1, 2);
pathweaver.core.validateEgoState(ego);
end

function agents = makeAgents(input)
template = struct('id', 0, 'class', "", 'positionWorldM', [0 0], ...
    'velocityWorldMps', [0 0], 'headingRad', 0, 'collisionRadiusM', 0, ...
    'positionCovarianceWorldM2', eye(2), 'timestampS', 0);
agents = repmat(template, 1, numel(input));
for k = 1:numel(input)
    agent = input(k);
    required = {'id', 'class', 'positionWorldM', 'velocityWorldMps', ...
        'headingRad', 'collisionRadiusM', ...
        'positionCovarianceWorldM2', 'timestampS'};
    assert(all(isfield(agent, required)), ...
        'PathWeaver:InvalidRequest', 'An agent state is incomplete.');
    assert(ismember(string(agent.class), ...
        ["pedestrian", "two_wheeler", "car", "animal"]), ...
        'PathWeaver:InvalidRequest', 'Unsupported PathWeaver actor class.');
    agents(k) = struct( ...
        'id', agent.id, ...
        'class', string(agent.class), ...
        'positionWorldM', reshape(agent.positionWorldM, 1, 2), ...
        'velocityWorldMps', reshape(agent.velocityWorldMps, 1, 2), ...
        'headingRad', agent.headingRad, ...
        'collisionRadiusM', agent.collisionRadiusM, ...
        'positionCovarianceWorldM2', agent.positionCovarianceWorldM2, ...
        'timestampS', agent.timestampS);
end
end

function obstacle = makeStaticObstacle(input)
assert(isfield(input, 'positionWorldM') && isfield(input, 'radiusM'), ...
    'PathWeaver:InvalidRequest', 'Static obstacle is incomplete.');
obstacle = struct('id', -1, 'geometryType', "circle", ...
    'positionWorldM', reshape(input.positionWorldM, 1, 2), ...
    'geometry', struct('radiusM', input.radiusM), ...
    'obstacleType', "carla_obstacle");
end
